// #region text
// One entry as plain text, for a bug report or an issue.
export function entryText(e, result) {
  const lines = [e.title, '', `Kind: ${KINDS[e.kind][0]}. Area: ${e.area}. ${e.how === 'reported' ? 'Reported' : 'Measured'} in ${e.browser}, ${e.date}.`];
  if (e.expected) lines.push('', `Expected: ${e.expected}`);
  lines.push('', `Actual: ${e.actual}`);
  if (result) lines.push('', `In ${navigator.userAgent}: ${result.happens === null ? 'not decided' : result.happens ? 'still happens' : 'does not happen'}. ${result.detail}`);
  lines.push('', `Workaround: ${e.fix}`, '', `Status: ${e.status}`, '', 'Where:', ...e.where.map(([path, what]) => `  https://html-in-canvas.page${path}${what ? ` (${what})` : ''}`), '', `Record: ${e.source}`);
  return lines.join('\n');
}
// #endregion text
