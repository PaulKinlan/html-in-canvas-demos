// Every HTML element, with the markup used to test it inside a drawable canvas.
//
//   tag    the element name (or "input type=…" for the input types)
//   group  key into GROUPS
//   html   test markup. {{video}}, {{audio}}, {{vtt}}, {{img}}, {{svg}} and {{other}} are filled
//          in at run time (see media.js). The element under test is the first match of `sel`.
//   sel    selector for the element under test inside the markup (default: the tag name)
//   make   for elements the parser will not create inside a <div>: build it with createElement
//
// What was found and what could be built with each element is in notes.js.

