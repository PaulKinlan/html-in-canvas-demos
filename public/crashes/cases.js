// #region text
// One entry as plain text, in the order a bug report wants.
export function reportText(c, counts = null, site = 'https://html-in-canvas.page') {
  const lines = [
    c.title,
    '',
    `Kind: ${{ crash: 'renderer or tab crash', loss: 'canvas contexts lost', blank: 'blank canvas' }[c.kind]}${c.related === false ? ' (not related to HTML-in-canvas)' : ''}`,
    `Browser: ${c.browser}`,
    `Evidence: ${c.how === 'measured' ? 'measured by a script or a page of the project' : 'reported from the project owner\'s phone'}, ${c.date}. ${c.isolated ? 'A page isolates it.' : 'Not isolated in a page of its own.'}`,
    '',
    'Steps:',
    ...c.steps.map((s, i) => `${i + 1}. ${s}`),
    '',
    `What happens: ${c.seen}`,
  ];
  if (c.notKnown) lines.push('', `Not known: ${c.notKnown}`);
  if (c.repro.length) lines.push('', 'Reproduce:', ...c.repro.map(([path, what]) => `- ${site}${path} (${what})`));
  if (counts?.n) lines.push('', `Reports from real devices in the last 30 days that match: ${counts.n}, the last ${new Date(counts.last).toISOString()}.`);
  lines.push('', `What the project does instead: ${c.now}`);
  return lines.join('\n');
}
// #endregion text
