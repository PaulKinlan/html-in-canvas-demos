#!/usr/bin/env node
// npm run build
//
// Writes the files the site needs that are assembled from many small source
// files. The outputs are in .gitignore: they are never committed, so no two
// branches can conflict in them. It is the `postinstall` script in package.json,
// so Workers Builds runs it (through its install step) before every deploy and
// every preview upload. `npm run check:jank` runs it before it serves the site,
// and you run it once before serving public/ yourself.
//
//   public/shared/pages.js   window.DEMO_GROUPS, window.DEMOS, window.PAGES,
//                            from the page.json files (see tools/site/pages.mjs)
//
// Other generators that write uncommitted output hook in here: export an
// async `build({ pages, menu })` from tools/<name>/site-build.mjs.
//
//   node tools/site/build.mjs            build
//   node tools/site/build.mjs --check    validate the page files, write nothing
//   node tools/site/build.mjs --list     print the pages, one per line
import { readdir, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { readPages, repoRoot } from './pages.mjs';

const args = new Set(process.argv.slice(2));

export async function buildSite({ write = true, quiet = false } = {}) {
  const site = await readPages();
  for (const w of site.warnings) console.warn(`warning: ${w}`);
  if (site.problems.length) {
    for (const p of site.problems) console.error(`error: ${p}`);
    throw new Error(`${site.problems.length} problem(s) in the page files`);
  }
  if (!write) return site;

  const strip = ({ jank, menu, order, added, ...rest }) => rest;
  const out = `// Generated by \`npm run build\` (tools/site/build.mjs) from the page.json files
// under public/. Do not edit and do not commit: change the page.json beside the page.
window.DEMO_GROUPS = ${JSON.stringify(site.groups)};
window.DEMOS = ${JSON.stringify(site.menu.map(strip), null, 1)};
window.PAGES = ${JSON.stringify(Object.fromEntries(Object.values(site.pages).map((p) => [p.href, strip(p)])), null, 1)};
`;
  await writeFile(path.join(repoRoot, 'public/shared/pages.js'), out);
  if (!quiet) console.log(`public/shared/pages.js: ${site.menu.length} menu entries, ${Object.keys(site.pages).length} page files`);

  // Generators owned by other tools.
  const toolsDir = path.join(repoRoot, 'tools');
  for (const e of (await readdir(toolsDir, { withFileTypes: true })).filter((d) => d.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const hook = path.join(toolsDir, e.name, 'site-build.mjs');
    if (!(await access(hook).then(() => true, () => false))) continue;
    const note = await (await import(pathToFileURL(hook))).build(site);
    if (!quiet && note) console.log(note);
  }
  return site;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const site = await buildSite({ write: !args.has('--check') && !args.has('--list') });
    if (args.has('--list')) {
      let group = null;
      for (const p of site.menu) {
        if (p.group !== group) { group = p.group; console.log(`\n${site.groups.find(([k]) => k === group)?.[1] ?? group}`); }
        console.log(`  ${p.href.padEnd(28)} ${p.title}`);
      }
      const rest = Object.values(site.pages).filter((p) => p.menu === false);
      if (rest.length) console.log(`\nNot in the menu\n${rest.map((p) => `  ${p.href}`).join('\n')}`);
    } else if (args.has('--check')) console.log(`${Object.keys(site.pages).length} page files are valid.`);
  } catch (e) { console.error(e.message); process.exit(1); }
}
