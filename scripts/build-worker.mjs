// Bundles everything in public/ into a single self-contained Worker module
// (dist/worker.js). Used for deploys through the Cloudflare API, where a
// single script upload is simpler than the static-assets upload flow.
// `npx wrangler deploy` uses wrangler.jsonc (static assets) instead.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, relative, extname } from 'node:path';

const root = new URL('../public/', import.meta.url).pathname;
const types = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.md': 'text/markdown; charset=utf-8',
};

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else yield p;
  }
}

const files = {};
for await (const p of walk(root)) {
  const path = '/' + relative(root, p);
  files[path] = [types[extname(p)] ?? 'application/octet-stream', await readFile(p, 'utf8')];
}

const worker = `// Generated by scripts/build-worker.mjs. Do not edit.
const FILES = ${JSON.stringify(files)};
export default {
  async fetch(request) {
    const url = new URL(request.url);
    let path = decodeURIComponent(url.pathname);
    if (path.endsWith('/')) path += 'index.html';
    let file = FILES[path];
    if (!file && FILES[path + '/index.html']) {
      return Response.redirect(url.origin + path + '/' + url.search, 301);
    }
    if (!file) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
    return new Response(file[1], {
      headers: {
        'content-type': file[0],
        'cache-control': 'no-cache',
        'x-content-type-options': 'nosniff',
      },
    });
  },
};
`;
await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
await writeFile(new URL('../dist/worker.js', import.meta.url), worker);
console.log(`dist/worker.js: ${Object.keys(files).length} files, ${worker.length} bytes`);
